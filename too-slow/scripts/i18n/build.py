import json, re, sys
sys.path.insert(0, 'scripts/i18n')
T = {}
for n in ('t1', 't2', 't3'):
    ns = {}
    exec(open(f'scripts/i18n/{n}.py').read(), ns)
    T.update(ns['T'])
keys = json.load(open(sys.argv[1]))
junk = {'tt','duo','tutorial','respawn','roll','crawl','steer','item','boost','slide','spin'}
missing = [k for k in keys if k not in T and k not in junk and re.search('[a-z]', k)]
print('missing', len(missing))
for m in missing: print('  ', m)
def q(s): return json.dumps(s, ensure_ascii=False)
rows = ',\n'.join('  [' + ', '.join(q(x) for x in [k, *v]) + ']' for k, v in T.items())
open('src/i18n/strings.ts', 'w').write('/* Generated by scripts/i18n/build.py: [English, it, es, fr, de, pt]. */\nexport const TABLE: string[][] = [\n' + rows + ',\n];\n')
print('rows', len(T))
