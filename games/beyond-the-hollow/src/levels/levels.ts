/**
 * Level data. Each level is a horizontal chain of authored 24-row segments (tilemaps in ASCII).
 *
 * Legend
 *  #  rock           =  one-way ledge     H  ladder/vine     ^ v  spikes up/down
 *  ~  water          a  acid              <  > water current (water + push)
 *  P  start          C  checkpoint        E  exit rift       i  hint   o  lore log
 *  B  crate          _  pressure plate    D  door (vertical stack)     w  web cocoon (charged shot)
 *  M  ancient mechanism (Pip)            h  hidden light-glass platform (Pip reveals)
 *  L  lamp           G  hiding spot       +  vitality orb
 *  !  arc emitter    r  stalactite        m  bounce cap       %  spore vent
 *  c  crawler        s  stalker           b  burrower         X  tide guardian   W  heart guardian (boss)
 * Markers sit in the cell directly above the floor they stand on.
 */
import type { ThemeKey } from '../art/themes';
import { CHAPTER2 } from './chapter2.ts';
import { CHAPTER3 } from './chapter3.ts';
import { CHAPTER4 } from './chapter4.ts';

export interface LevelDef {
  id: string;
  name: string;
  subtitle: string;
  theme: ThemeKey;
  music: 'station' | 'forest' | 'caverns' | 'ocean' | 'heart' | 'ice' | 'foundry' | 'ruins' | 'keepers' | 'abyss' | 'seed';
  /** Pip's Light Thread (grapple) is available */
  hook?: boolean;
  /** Pip's Echo (present/past switching) is available */
  eco?: boolean;
  /** which story chapter this part belongs to (1-based) */
  chapter: number;
  /** slippery ice floors */
  ice?: boolean;
  /** boss presented when the arena is entered */
  boss?: { name: string; sub: string; music: 'boss' | 'boss2' | 'boss3' | 'boss4' };
  darkness: number;
  backWall: boolean;
  doubleJump: boolean;
  intro: string[];
  hints: string[];
  lore: string[];
  segments: string[][];
}

export interface ChapterDef {
  roman: string;
  title: string;
  /** closing lines shown on the chapter's ending screen */
  ending: string[];
  next?: string;
}

