import { chromium } from '@playwright/test';
const out = process.argv[2];
const url = process.argv[3] || 'http://127.0.0.1:4188/';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(`${m.type()}: ${m.text()}`); });
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`));
const t0 = Date.now();
await page.goto(url);
await page.waitForSelector('#menu:not([hidden])', { timeout: 60000 });
console.log('menu after ms', Date.now() - t0);
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/menu.png` });
await page.click('#btn-play');
await page.waitForTimeout(1500);
const d0 = await page.evaluate(() => window.__THREE_GAME_DIAGNOSTICS__);
console.log('start', JSON.stringify(d0.player), d0.screen, JSON.stringify(d0.renderer), JSON.stringify(d0.physics), 'fps', d0.fps.toFixed(1));
await page.screenshot({ path: `${out}/play-start.png` });
await page.keyboard.down('KeyW');
await page.waitForTimeout(1500);
await page.keyboard.down('ShiftLeft');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/play-run.png` });
await page.keyboard.up('ShiftLeft');
await page.keyboard.press('Space');
await page.waitForTimeout(250);
const air = await page.evaluate(() => window.__THREE_GAME_DIAGNOSTICS__.player);
await page.screenshot({ path: `${out}/play-jump.png` });
await page.waitForTimeout(800);
await page.keyboard.up('KeyW');
await page.waitForTimeout(500);
const d1 = await page.evaluate(() => window.__THREE_GAME_DIAGNOSTICS__);
console.log('air', JSON.stringify(air));
console.log('after', JSON.stringify(d1.player), d1.screen, 'discovered', d1.discovered, 'fps', d1.fps.toFixed(1), JSON.stringify(d1.stats));
await page.keyboard.press('Tab');
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/map.png` });
console.log('errors', errors.length, errors.slice(0, 15).join('\n'));
await browser.close();
