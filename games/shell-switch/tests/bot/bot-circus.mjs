import { start, possess, exit, park, finish } from './common.mjs';
const B = await start('circus');
await B.walkTo(31, 0, 0.6, 90000, false);
await B.press('ability', 100);
await B.waitFlag('bigTopOpen', 30000);
await B.log('C1');
await B.simWait(12);
await B.walkTo(32, 9.5, 0.6, 90000, false);
await B.press('ability', 100);
await B.waitFlag('mooseDistracted', 15000);
await exit(B);
await possess(B, 'slink', 'thief');
await B.approach(B.npcPos('moose'), /Pickpocket/, 'f');
await B.press('ability', 100);
await B.waitFor(() => window.__THREE_GAME_DIAGNOSTICS__.game.items.includes('keycard'), null, 15000);
await B.simWait(2);
await B.approach(B.objPos('trailer'), /Keycard/);
await B.press('interact', 100);
await B.waitFlag('door:trailer');
await B.walkTo(30, 16.2, 0.5, 90000, false);
await B.approach(B.objPos('fuse-pickup'), /Take/);
await B.press('interact', 100);
await B.waitFlag('got:fuse-pickup');
await B.log('C2');
await B.walkTo(30, 12, 0.6); await B.walkTo(34, 0, 0.6); await B.walkTo(40, 1, 0.6);
await B.approach(B.objPos('cannon'), /Install/);
await B.press('interact', 100);
await B.waitFlag('cannonFuse');
await park(B, 'strongman', 40, 0, 0.5);
await exit(B);
await possess(B, 'brick', 'strongman');
for (let i = 0; i < 2; i += 1) {
  await B.approach(B.objPos('cannon'), /Turn cannon/, 'f');
  await B.press('ability', 100);
  await B.waitIdle();
  await B.simWait(0.5);
}
await B.waitFlag('cannonAimed', 5000);
await exit(B);
await B.approach(B.objPos('cannon'), /Climb in/);
await B.press('interact', 100);
await B.waitFor(() => window.__SHELL__.game.controlled.pos.y > 6 && !window.__SHELL__.game.launching, null, 15000);
await B.approach(B.objPos('core-circus'), /Star Core/, 'e', 8000);
await B.press('interact', 100);
await B.waitFlag('core:circus');
await finish(B, 'bot-circus');
