import { start, possess, exit, park, finish } from './common.mjs';
const B = await start('mall');
await B.walkTo(-45, 2);
await B.approach(B.objPos('stove-mall'), /Cook/, 'f');
await B.press('ability', 100);
await B.waitFor(() => window.__THREE_GAME_DIAGNOSTICS__.game.items.includes('burger'), null, 20000);
await B.approach(B.npcPos('waldo'), /Give/);
await B.press('interact', 100);
await B.waitFlag('waldoFed');
await B.page.waitForTimeout(1500);
await B.walkTo(-40, 16.5); await B.walkTo(-40, 22.5);
await B.approach(B.objPos('mic-pickup'), /Take/);
await B.press('interact', 100);
await B.waitFlag('got:mic-pickup');
await B.log('M1');
await exit(B);
await B.walkTo(-40, 16.5); await B.walkTo(-40, -11);
await B.face(-42, -15.5);
await B.key('KeyW', true); await B.press('jump', 400); await B.key('KeyW', false);
await possess(B, 'velvet', 'singer');
await B.log('as velvet');
// gather fans then walk into the audience circle singing
await B.walkTo(-36, -5, 1.0, 90000, false);
await B.press('ability', 200);
await B.walkTo(-42, -7.5, 0.6, 90000, false);
await B.waitFlag('showDone', 25000);
await B.log('M2');
// M3: lure Facet away, then Slink picks the lock
await B.page.waitForTimeout(500);
await B.walkTo(-48.5, -12, 0.6, 90000, false);
await B.press('ability', 200);
await B.walkTo(-44, -6, 0.6, 90000, false);
await B.waitFlag('facetAway', 15000);
await park(B, 'thief', -47, -11, 0);
await exit(B);
await possess(B, 'slink', 'thief');
await B.approach(B.objPos('sparkle'), /Pick lock/, 'f');
await B.press('ability', 100);
await B.waitFlag('door:sparkle', 15000);
await B.walkTo(-55.5, -14, 0.6);
await B.approach(B.objPos('core-mall'), /Star Core/);
await B.press('interact', 100);
await B.waitFlag('core:mall');
await finish(B, 'bot-mall');
