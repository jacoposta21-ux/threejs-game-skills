/** UI flow smoke test through real clicks/keys: menus, pause, shift end, rewarded ad, save, garage. */
import { chromium } from 'playwright';
import { existsSync } from 'node:fs';
const url = process.argv[2] || 'http://127.0.0.1:4173/';
const exe = existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : undefined;
const browser = await chromium.launch({ executablePath: exe, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
const debugLog = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); if (m.type() === 'debug') debugLog.push(m.text()); });
page.on('pageerror', (e) => errors.push(e.message));
const ok = [];
const check = (name, cond) => { ok.push(`${cond ? 'PASS' : 'FAIL'} ${name}`); };
await page.goto(url);
await page.waitForFunction(() => window.__pw, null, { timeout: 90000 });
await page.evaluate(() => localStorage.setItem('pw_save_v1', '{corrupted'));
await page.reload();
await page.waitForFunction(() => window.__pw, null, { timeout: 90000 });
check('corrupted save -> boots to title', (await page.evaluate(() => window.__pw.state())) === 'title');
await page.click('#title [data-a=play]');
check('select screen', (await page.evaluate(() => window.__pw.state())) === 'select');
check('harbour locked', await page.locator('#select .tab.locked').count() === 2);
await page.click('#select .turn[data-t="1"]');
check('shift 1 playing', (await page.evaluate(() => window.__pw.state())) === 'playing');
await page.keyboard.press('Escape');
check('Escape pauses', (await page.evaluate(() => window.__pw.state())) === 'paused');
await page.click('#pause [data-a=resume]');
check('resume', (await page.evaluate(() => window.__pw.state())) === 'playing');
await page.evaluate(() => window.dispatchEvent(new Event('blur')));
check('blur pauses', (await page.evaluate(() => window.__pw.state())) === 'paused');
await page.click('#pause [data-a=resume]');
// real key input moves the scooter
await page.evaluate(() => { window.__pw.game.input.keys.add('KeyW'); window.__pw.simulate(2); window.__pw.game.input.keys.clear(); });
const sp = await page.evaluate(() => window.__pw.game.sim.scooter.speed);
check('W accelerates (' + sp.toFixed(1) + ' m/s)', sp > 4);
await page.evaluate(() => { window.__pw.autopilot(true); for (let i = 0; i < 60 && window.__pw.state() !== 'end'; i++) window.__pw.simulate(3); });
check('shift ends', (await page.evaluate(() => window.__pw.state())) === 'end');
const save1 = await page.evaluate(() => JSON.parse(localStorage.getItem('pw_save_v1')));
check('save written: stars[0]=' + save1.stars[0] + ' coins=' + save1.coins, save1.stars[0] >= 1 && save1.coins > 0);
await page.click('#end [data-a=double]');
await page.waitForSelector('.ad-stub', { timeout: 3000 });
check('ad stub overlay shown', true);
await page.waitForSelector('.ad-stub', { state: 'detached', timeout: 6000 });
const save2 = await page.evaluate(() => JSON.parse(localStorage.getItem('pw_save_v1')));
check('double tips doubled coins ' + save1.coins + ' -> ' + save2.coins, save2.coins === save1.coins * 2);
await page.click('#end [data-a=garage]');
await page.click('#garage [data-u=motor]');
const save3 = await page.evaluate(() => JSON.parse(localStorage.getItem('pw_save_v1')));
check('bought engine lvl ' + save3.upgrades.motor, save3.upgrades.motor === 1 && save3.coins === save2.coins - 60);
await page.click('#garage [data-a=back]');
check('back to end screen', (await page.evaluate(() => window.__pw.state())) === 'end');
await page.click('#end [data-a=next]');
check('next shift = 2', (await page.evaluate(() => window.__pw.game.turn)) === 2);
await page.keyboard.press('F1');
check('debug panel (F1)', await page.locator('#debug').count() === 1);
await page.click('#debug [data-d=tp]');
await page.evaluate(() => window.__pw.simulate(1));
check('debug teleport -> delivery', (await page.evaluate(() => window.__pw.shift().delivered)) >= 1);
const ev = ['session_start', 'level_start', 'level_complete', 'delivery', 'upgrade_bought', 'ad_rewarded_shown', 'booster_used'];
for (const e of ev) check('analytics ' + e, debugLog.some((l) => l.includes('[analytics] ' + e)));
check('no console errors', errors.length === 0);
console.log(ok.join('\n'));
if (errors.length) console.log(errors.join('\n'));
await browser.close();
process.exit(ok.some((l) => l.startsWith('FAIL')) ? 1 : 0);
